// Turn the packaged _site into a Cloudflare Workers static-assets bundle.
// Run after build/package-pages.mjs. Writes _site/_redirects and _site/_headers,
// which Cloudflare reads as configuration and never serves.
//
// wrangler.jsonc sets html_handling to "none", so Cloudflare serves exact file
// paths only. Every URL shape GitHub Pages resolved implicitly is spelled out
// here instead: canonical .html URLs stay 200, extensionless URLs 301 to them,
// directory indexes are rewritten, and instant meta-refresh pages become real
// 301s. Cloudflare applies _redirects before it looks for a file, so a rule
// always wins over an asset at the same path.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

// Pages merged or retired by hand, as [from, to] URL paths. Add one whenever a
// page is removed, so its old URL keeps its links and citations.
export const MANUAL_REDIRECTS = [];

// Pages renamed in git, as [old file, new file]. package-pages.mjs writes a
// redirect stub at the old path into the artifact only (served as a 301 below),
// so in git the rename stays a pure rename and open branches that edit the old
// file still merge into the new one.
export const RENAMED = [['ai-readiness-tool.html', 'consulenza-aeo-geo.html']];

// Cloudflare's hard limits for a _redirects file.
const MAX_STATIC_RULES = 2000;
const MAX_RULE_LENGTH = 1000;

export const HEADERS = `# Generated by build/package-cloudflare.mjs; edit it there.
/*
  X-Content-Type-Options: nosniff
  Strict-Transport-Security: max-age=31536000
  Access-Control-Allow-Origin: *

# GitHub Pages' ten minutes. Many pages load CSS and JS without a ?v= stamp, and
# _headers cannot tell a 404 from a file, so a longer max-age on a prefix would
# also pin a missing image in caches after it is uploaded.
/*.css
  Cache-Control: public, max-age=600
  Content-Type: text/css; charset=utf-8
/*.js
  Cache-Control: public, max-age=600
  Content-Type: text/javascript; charset=utf-8
/*.mjs
  Cache-Control: public, max-age=600
  Content-Type: text/javascript; charset=utf-8
/img/*
  Cache-Control: public, max-age=600
/assets/*
  Cache-Control: public, max-age=600
/downloads/*
  Cache-Control: public, max-age=600

# Cloudflare's production edge sends text types without a charset (GitHub Pages
# and wrangler dev include it). Crawler libraries such as Python requests then fall
# back to Latin-1 and garble the accents in llms.txt, robots.txt and page text.
/*.html
  Content-Type: text/html; charset=utf-8
/*.txt
  Content-Type: text/plain; charset=utf-8
/*.webmanifest
  Content-Type: application/manifest+json; charset=utf-8

# workers.dev and preview URLs duplicate the whole site; keep them out of every index.
https://:worker.:account.workers.dev/*
  X-Robots-Tag: noindex
`;

const REFRESH = /<meta\s+http-equiv=["']refresh["']\s+content=["']\s*0\s*;\s*url=([^"']+)["']/i;

// The URL a packaged HTML file is published at.
export function urlFor(file) {
  if (file === 'index.html') return '/';
  if (file.endsWith('/index.html')) return '/' + file.slice(0, -'index.html'.length);
  return '/' + file;
}

// Every URL that reaches a file, mapped to the rule that serves it.
export function rulesFor(file, html) {
  const url = urlFor(file);
  const refresh = html.match(REFRESH);
  if (refresh) {
    const target = new URL(refresh[1], 'https://niuexa.ai' + url).pathname;
    if (url.endsWith('/')) {
      const sources = url === '/' ? ['/', '/index'] : [url, url.slice(0, -1), url + 'index.html', url + 'index'];
      return sources.map(from => [from, target, 301]);
    }
    return [[url, target, 301], [url.slice(0, -'.html'.length), target, 301]];
  }
  // Pages also answered /index and /<dir>/index; send them to the directory URL.
  if (url === '/') return [['/', '/index.html', 200], ['/index', '/', 301]];
  if (url.endsWith('/')) return [[url.slice(0, -1), url, 301], [url, url + 'index.html', 200], [url + 'index', url, 301]];
  return [[url.slice(0, -'.html'.length), url, 301]];
}

async function htmlFiles(dir, base = dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await htmlFiles(path, base));
    else if (entry.name.endsWith('.html')) out.push(relative(base, path).split('\\').join('/'));
  }
  return out.sort();
}

export async function buildRedirects(site) {
  const rules = [];
  for (const [from, to] of MANUAL_REDIRECTS) rules.push([from, to, 301]);
  for (const file of await htmlFiles(site)) {
    // 404.html is served by not_found_handling, never at a URL of its own.
    if (file === '404.html') continue;
    rules.push(...rulesFor(file, await readFile(join(site, file), 'utf8')));
  }
  const seen = new Map();
  const unique = [];
  for (const rule of rules) {
    // A manual redirect listed first overrides the generated rule for the same URL.
    if (seen.has(rule[0])) continue;
    seen.set(rule[0], rule);
    unique.push(rule);
  }
  const loops = unique.filter(([from, to, status]) => status === 301 && from === to);
  if (loops.length) throw new Error(`redirect loops: ${loops.map(r => r[0]).join(', ')}`);
  if (unique.length > MAX_STATIC_RULES) throw new Error(`${unique.length} redirects exceed Cloudflare's ${MAX_STATIC_RULES}`);
  const lines = unique.map(([from, to, status]) => `${from} ${to} ${status}`);
  const long = lines.find(line => line.length > MAX_RULE_LENGTH);
  if (long) throw new Error(`redirect longer than ${MAX_RULE_LENGTH} characters: ${long.slice(0, 80)}…`);
  return lines;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = resolve(import.meta.dirname, '..');
  const site = join(root, '_site');
  const lines = await buildRedirects(site);
  await writeFile(join(site, '_redirects'), `# Generated by build/package-cloudflare.mjs; edit it there.\n${lines.join('\n')}\n`);
  // Directory URLs such as / and /en/ are served from index.html but do not end in
  // .html, so each gets its own charset rule.
  const dirs = (await htmlFiles(site)).map(urlFor).filter(url => url.endsWith('/'));
  const dirRules = dirs.map(url => `${url}\n  Content-Type: text/html; charset=utf-8`).join('\n');
  await writeFile(join(site, '_headers'), `${HEADERS}\n# Directory index pages.\n${dirRules}\n`);
  console.log(`Wrote ${lines.length} redirect rules and the headers file into ${relative(root, site)}.`);
}
